#!/usr/bin/env python3
"""Build mockups/painel.data.js from the saved web/api/lake reports and the AI diff of each gateway."""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

from loguru import logger

from src.scripts.diff_fontes import GATEWAYS

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ("web", "api", "lake")
LABELS = {"buygoods": ("BuyGoods", "GMT-4"), "pagamerican": ("PagAmerican", "UTC")}
DIFF_KEYS = ("tolerancia", "resumo", "contexto", "contas")


def _month(day: date) -> Path:
    return Path(f"{day.year:04d}") / f"{day.month:02d}"


def latest_diff_day(root: Path, gateway: str) -> date | None:
    """The panel needs the diff, so the latest panel day is the latest diff saved for the gateway."""
    days = [
        date.fromisoformat(path.stem.removeprefix("diff_ai_"))
        for path in (root / "exports" / gateway / "diff").glob("*/*/diff_ai_*.json")
    ]
    return max(days, default=None)


def build_panel_data(root: Path, gateway: str, day: date) -> dict:
    exports = root / "exports" / gateway
    diff_path = exports / "diff" / _month(day) / f"diff_ai_{day.isoformat()}.json"
    if not diff_path.exists():
        raise FileNotFoundError(
            f"{diff_path} not found; run `make diff GATEWAY={gateway} DATE={day.isoformat()}` first"
        )
    prefix = GATEWAYS[gateway][1]
    sources = {}
    for source in SOURCES:
        path = exports / source / _month(day) / f"{prefix}_{day.isoformat()}.json"
        # A source that has not landed yet shows as accounts missing, not as an error.
        sources[source] = json.loads(path.read_text(encoding="utf-8"))["contas"] if path.exists() else {}
    diff = json.loads(diff_path.read_text(encoding="utf-8"))
    label, tz = LABELS[gateway]
    return {
        "label": label,
        "day": day.isoformat(),
        "tz": tz,
        "sources": sources,
        "diff": {key: diff[key] for key in DIFF_KEYS},
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    for gateway in LABELS:
        parser.add_argument(
            f"--{gateway}-date",
            type=date.fromisoformat,
            help=f"{LABELS[gateway][0]} day YYYY-MM-DD (default: latest day with a diff)",
        )
    parser.add_argument("--output-root", type=Path, default=ROOT, help="Root that holds exports/ (default: project)")
    parser.add_argument(
        "--out", type=Path, default=ROOT / "mockups" / "painel.data.js", help="Generated data file for the panel"
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    logger.remove()
    logger.add(sys.stderr, level="INFO", colorize=sys.stderr.isatty())
    root = args.output_root.resolve()
    reports = {}
    for gateway in LABELS:
        day = getattr(args, f"{gateway}_date") or latest_diff_day(root, gateway)
        if day is None:
            raise RuntimeError(f"No diff saved for {gateway}; run `make diff GATEWAY={gateway}` first")
        reports[gateway] = build_panel_data(root, gateway, day)
        logger.info("{} {}: {}", gateway, day, {s: len(v) for s, v in reports[gateway]["sources"].items()})
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "// Generated by `make painel` from exports/; do not edit or commit (real account data).\n"
        f"window.REPORTS = {json.dumps(reports, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    logger.info("Saved panel data: {}", args.out)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as error:
        logger.exception("Panel data generation failed")
        raise SystemExit(1) from error
